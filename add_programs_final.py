def extract_code(name):
    """Извлекает код специальности из названия."""
    match = re.match(r'^(\d+\.\d+\.\d+)', name)
    return match.group(1) if match else ""


def add_programs():
    """Добавляет все программы в БД."""
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    
    # Проверяем, есть ли таблица programs
    c.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='programs'")
    if not c.fetchone():
        print("❌ Таблица programs не найдена. Сначала создайте таблицу.")
        conn.close()
        return
    
    # Очищаем таблицу
    c.execute("DELETE FROM programs")
    
    count = 0
    for prog_id, name, budget_places in PROGRAMS_DATA:
        code = extract_code(name)
        
        c.execute('''INSERT OR REPLACE INTO programs (id, code, title, budget_places) 
                     VALUES (?, ?, ?, ?)''',
                  (prog_id, code, name, budget_places))
        count += 1
        
        # Показываем прогресс
        if count % 10 == 0:
            print(f"  Прогресс: {count}/91")
    
    conn.commit()
    conn.close()
    
    print(f"\n🎉 Успешно добавлено {count} программ в БД!")
    print(f"📊 Всего программ: {len(PROGRAMS_DATA)}")


def verify_db():
    """Проверяет, что программы добавились."""
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    
    c.execute("SELECT COUNT(*) FROM programs")
    count = c.fetchone()[0]
    
    print(f"\n📊 В БД сейчас {count} программ")
    
    # Показываем первые 5
    c.execute("SELECT id, code, title, budget_places FROM programs LIMIT 5")
    print("\n📋 Примеры программ:")
    for row in c.fetchall():
        print(f"  {row[0]}: {row[1]} {row[2][:40]}... (КЦП: {row[3]})")
    
    conn.close()


