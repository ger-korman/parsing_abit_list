def extract_budget_places(name):
    """Извлекает КЦП из названия программы."""
    import re
    match = re.search(r'КЦП:\s*(\d+)', name)
    return int(match.group(1)) if match else 0


def extract_code(name):
    """Извлекает код специальности из названия."""
    import re
    match = re.search(r'^(\d+\.\d+\.\d+)', name)
    return match.group(1) if match else ""

def add_programs():
    """Добавляет все программы в БД."""
    
    # Проверяем, совпадают ли длины списков
    if len(program_ids) != len(program_names):
        print(f"❌ Ошибка: ID ({len(program_ids)}) и названий ({len(program_names)}) не совпадают!")
        return
    
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    
    # Очищаем таблицу программ (опционально)
    # c.execute("DELETE FROM programs")
    
    count = 0
    for prog_id, name in zip(program_ids, program_names):
        code = extract_code(name)
        budget_places = extract_budget_places(name)
        
        c.execute('''INSERT OR REPLACE INTO programs (id, code, title, budget_places) 
                     VALUES (?, ?, ?, ?)''',
                  (prog_id, code, name, budget_places))
        count += 1
        print(f"✅ {count:2d}. {prog_id} → {code} {name[:60]}...")
    
    conn.commit()
    conn.close()
    
    print(f"\n🎉 Успешно добавлено {count} программ в БД!")

if __name__ == "__main__":
    add_programs()